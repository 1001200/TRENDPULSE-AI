import React from 'react'
import { Sparkles, Flame, CheckCircle, ArrowRight, Loader } from 'lucide-react'
import { useStore } from '../context/StoreContext'
import { formatCurrency, formatPercent, shortenProduct } from '../utils/formatters'
import {
  BarChart, Bar, XAxis, YAxis, Tooltip, ResponsiveContainer, CartesianGrid
} from 'recharts'

const ChartTooltipStyle = {
  contentStyle: {
    background: '#FFFFFF',
    border: '3px solid #121212',
    borderRadius: 0,
    fontSize: '0.84rem',
    fontWeight: 800,
    fontFamily: "'Outfit', sans-serif",
    color: '#121212',
    boxShadow: '4px 4px 0px 0px #121212',
    padding: '8px 14px',
  },
  itemStyle: {
    color: '#121212',
    fontWeight: 800,
  }
}

export default function TrendsPage() {
  const { result, loading } = useStore()

  if (loading && !result) {
    return (
      <div className="page-container flex-center" style={{ minHeight: '60vh' }}>
        <div style={{ textAlign: 'center' }}>
          <Loader size={38} className="spin text-indigo" strokeWidth={2.5} />
          <p className="text-muted mt-md font-heading" style={{ fontWeight: 800, textTransform: 'uppercase' }}>
            MINING TIKTOK &amp; SOCIAL AESTHETIC VELOCITIES…
          </p>
        </div>
      </div>
    )
  }

  const social = result?.social_curation || {}
  const rawAesthetics = social.aesthetic_velocity?.top_aesthetics_by_revenue || social.aesthetic_velocity?.aesthetics || []
  const aesthetics = rawAesthetics.map(a => ({
    aesthetic: a.aesthetic,
    revenue: a.revenue,
    units: a.units_sold,
    share: a.revenue_share_percentage,
  }))

  const sourcing = social.sourcing_recommendations?.sourcing_checklist || []
  const topAestheticHunt = social.sourcing_recommendations?.top_aesthetic_to_hunt
  const topSizeHunt = social.sourcing_recommendations?.top_size_to_hunt

  return (
    <div className="page-container">
      {/* Header */}
      <div className="card mb-md animate-in card-glyph-circle" style={{ padding: '20px 24px', background: 'var(--bauhaus-white)' }}>
        <div className="flex-between" style={{ flexWrap: 'wrap', gap: 12 }}>
          <div>
            <div style={{ display: 'flex', alignItems: 'center', gap: 10, marginBottom: 4 }}>
              <h2 style={{ margin: 0, fontSize: '1.5rem', fontWeight: 900, textTransform: 'uppercase' }}>
                VIRAL TRENDS &amp; AESTHETIC VELOCITY
              </h2>
              <span className="badge badge--amber">TIKTOK &amp; REELS</span>
              <span className="badge badge--indigo">NEXT DROP CURATION</span>
            </div>
            <div className="text-xs" style={{ fontWeight: 700, color: 'var(--text-muted)', textTransform: 'uppercase' }}>
              ALIGN MERCHANDISING WITH VIRAL SOCIAL SIGNALS AND REAL REVENUE DEMAND
            </div>
          </div>
        </div>
      </div>

      {/* Sourcing Guidance Hero Banner */}
      {topAestheticHunt && (
        <div className="card mb-md animate-in" style={{ borderLeft: '10px solid var(--bauhaus-yellow)', background: 'var(--bauhaus-yellow-lt)' }}>
          <div className="flex-between" style={{ flexWrap: 'wrap', gap: 16 }}>
            <div>
              <div className="badge badge--rose" style={{ marginBottom: 6 }}>
                <Flame size={12} /> HIGHEST CONVERTING AESTHETIC
              </div>
              <h3 style={{ margin: 0, fontSize: '1.35rem', fontWeight: 900, textTransform: 'uppercase' }}>
                TARGET AESTHETIC FOR NEXT DROP: <span className="text-indigo">{topAestheticHunt}</span>
              </h3>
              <p className="text-sm" style={{ fontWeight: 700, marginTop: 4, marginBottom: 0 }}>
                Historical demand signals show <span className="text-rose">Size {topSizeHunt}</span> sells at 3.2x the velocity of other sizes. Focus next production run here.
              </p>
            </div>
            <span className="badge badge--indigo" style={{ padding: '8px 16px', fontSize: '0.85rem' }}>
              RECOMMENDED SIZE: {topSizeHunt}
            </span>
          </div>
        </div>
      )}

      {/* Aesthetic Velocity Bar Chart */}
      <div className="card mb-md animate-in animate-in-delay-1 card-glyph-square">
        <div className="card-title">TIKTOK &amp; INSTAGRAM REELS AESTHETIC REVENUE RANKING</div>
        <p className="text-xs text-muted" style={{ textTransform: 'uppercase', fontWeight: 700, marginBottom: 16 }}>
          REAL REVENUE GENERATED BY DESIGN AESTHETIC CATEGORY
        </p>
        {aesthetics.length === 0 ? (
          <div style={{ padding: '30px', textAlign: 'center', background: '#F5F5F5', border: '2px dashed #121212' }}>
            <p className="font-heading" style={{ fontWeight: 800, textTransform: 'uppercase', margin: 0 }}>
              No aesthetic trends detected for this dataset yet.
            </p>
          </div>
        ) : (
          <ResponsiveContainer width="100%" height={320}>
            <BarChart data={aesthetics} layout="vertical">
              <CartesianGrid stroke="#121212" strokeDasharray="0" opacity={0.15} />
              <XAxis type="number" tick={{ fill: '#121212', fontSize: 11, fontWeight: 700 }} tickFormatter={v => `₹${(v/1000).toFixed(0)}k`} />
              <YAxis dataKey="aesthetic" type="category" width={190} tick={{ fill: '#121212', fontSize: 11, fontWeight: 700 }} />
              <Tooltip {...ChartTooltipStyle} formatter={(v) => [formatCurrency(v), 'Revenue']} />
              <Bar dataKey="revenue" fill="#1040C0" stroke="#121212" strokeWidth={2} radius={[0, 0, 0, 0]} />
            </BarChart>
          </ResponsiveContainer>
        )}
      </div>

      {/* Sourcing Checklist */}
      {sourcing.length > 0 && (
        <div className="card animate-in animate-in-delay-2 card-glyph-triangle">
          <div className="card-title">📋 WHAT TO SOURCE NEXT (PROCUREMENT CHECKLIST)</div>
          <div className="sourcing-list">
            {sourcing.map((s, i) => (
              <div key={i} className="sourcing-item">
                <div style={{ display: 'flex', alignItems: 'center', gap: 14 }}>
                  <span className={`badge ${s.priority?.includes('High') || s.priority === 'High' ? 'badge--rose' : 'badge--amber'}`}>
                    {s.priority || 'P1'}
                  </span>
                  <div>
                    <strong style={{ fontSize: '1rem', textTransform: 'uppercase' }}>{s.aesthetic}</strong>
                    <div className="text-xs" style={{ fontWeight: 700, color: 'var(--text-muted)' }}>
                      TARGET SIZE: <span className="text-rose">{s.top_size}</span>
                    </div>
                  </div>
                </div>
                <div style={{ textAlign: 'right' }}>
                  <div className="font-mono text-indigo" style={{ fontSize: '1.05rem', fontWeight: 900 }}>
                    {formatCurrency(s.avg_price)}
                  </div>
                  <div className="text-xs" style={{ fontWeight: 700, color: 'var(--text-muted)' }}>
                    TARGET RETAIL PRICE
                  </div>
                </div>
              </div>
            ))}
          </div>
        </div>
      )}
    </div>
  )
}
